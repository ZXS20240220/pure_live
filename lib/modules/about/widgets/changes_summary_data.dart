- **阅读与复制**：正文收起时截断 3 行，左键展开 / 收起，悬浮显示完整内容 tooltip；用户名过长渐隐截断并带 tooltip；文字不可选中拖拽，右键任意位置一键复制 SC 内容。
- **斗鱼重复根治**：同一条 SC 会触发携带标价与实付价两种事件，按价格正确配对去重，根治重复显示；手动刷新仅清除已到期 SC，保留未到期项；同房间重试 / 切线路 / 切画质不再清空未到期付费留言。
- **历史稳定性**：斗鱼历史 SC 获取保存服务端下发的 Cookie 并带重试机制，进房前发出的未过期 SC 也能可靠显示。
- **本地发送**：本地互动体验支持发送本地 SC（仅本机显示，随本地弹幕清屏与退出直播间一并清理）。

### 飘屏弹幕

- **同屏上限可配置**：飘屏同屏数量上限由固定 48 提为用户设置（10~200，默认 48），带说明文字，随设置持久化并纳入备份链路。
- **重复弹幕聚合**：时间窗口内的重复刷屏弹幕合并计数：首条立即显示（零延迟），重复内容不再逐条刷屏，窗口结束时补发一条「原文 ×N」汇总（N 为窗口内实际条数，如「666 ×3」），携带首条发送者信息；与「重复弹幕过滤」并存且优先生效，两者共用同一时间窗口设置，本地发送的弹幕不参与聚合，关闭开关立即补发未过期的汇总，切换直播间自动丢弃残留分组。
- **丢弃透明化**：弹幕洪峰超出承载被丢弃时，弹幕列表左上角显示灰色「已隐藏 N 条弹幕」徽标（鼠标可穿透、不遮挡操作，无丢弃时自动隐藏），切换直播间后重新统计。
- **宽度自适应速度**：飘屏速度随播放器实际宽度自适应缩放（参考宽度 1280px，缩放区间 0.4×~1.5×），窄窗口不显过慢、宽窗口不显过快，可开关回到固定速度。
- **密度档位**：新增「正常 / 较多 / 重叠」三档对齐 B 站策略：较多 = 轨道安全间距减半；重叠 = 间距减半 + 允许同轨重叠（安全间距全占用时回退最空闲轨道而非丢弃）+ 整体透明度降至 55%，海量弹幕下按需取舍密度与可读性。
- **安全间距修复**：轨道安全间距由固定 40px 改为随弹幕字号自适应（字号 ×1.5，限制 16~40px），大字号下不再误判重叠。
- **渲染容错**：单条飘屏渲染异常不再中断整层绘制，弹幕洪峰下飘屏不再整体消失。

### 稳定性

- 直播画面四周无缩放热区，窗口缩放 / 全屏切换不黑闪。
- 下播或连接失败时侧栏正常显示。
- 连续刷新不会导致内容消失；视频设置页渲染完整。

