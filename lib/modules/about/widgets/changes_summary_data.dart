- **弹幕信息弹窗**：右键弹幕弹出详细信息弹窗（用户名、内容、等级、粉丝牌、UID、颜色、时间等，有则显示），点击任意信息项一键复制对应内容，弹窗底部保留「用户名: 内容」整条复制。
- **数值设置直编**：弹幕设置中的数值项支持点击直接输入编辑（全选回显、Enter 提交 / Esc 取消、非法输入回退原值、按步长对齐并限制在合法区间），保留加减按钮交互。

### 醒目留言（SC）

- **卡片展示**：醒目留言以卡片形式覆盖显示；价格按「实付(标价)」格式展示，连续重复的 SC 自动合并为一条，不再逐条刷屏。
