## 八、搜索模块与网页浏览修复

### 网页搜索无法加载（最终结论）

网页搜索 WebView「永远加载不出来」的排查经历了两轮：最初的「三处激进回调」假设（拦截内部导航、错误回调置失败、loadUrl 异常置失败）已被用户修复但测试中仍然复现，最终通过运行时证据链定位到真正的深层原因：

1. **修复从未进入被测试的构建（决定性证据）**：被测试的 Release exe 构建时间早于源码修复时间，`build/` 下仅有该旧二进制，所有修复都不在其中——「修复失败」的观察建立于过期构建之上。
2. **运行时证据指向「WebView2 环境存活但导航从未提交」**：WebView2 用户数据目录中浏览器/GPU 子进程存活，但 History 数据库零导航记录——即原生环境创建成功、页面加载从未发起，与「插件原生创建静默失败时 `onWebViewCreated` 永不触发且无任何报错」的插件已知缺陷表象吻合（未捕获的异步错误，UI 呈现无限空白 loading）。
3. **残留风险差异**：基础版 `shouldOverrideUrlLoading` 在 controller 身份不匹配时返回 `CANCEL`，把身份守卫错误地用作导航策略；首次导航若被静默取消同样呈现「永远加载不出来」。开发版始终返回 `ALLOW`。

最终修复（`web_search_controller.dart`）：

- **移除导航 CANCEL 策略**：`shouldOverrideUrlLoading` 始终返回 `ALLOW`（对齐开发版），身份守卫仅让其他回调忽略过期 controller 的事件，不再影响导航放行。
- **新增创建看门狗**：初始化后 10 秒内 `onWebViewCreated` 未触发（`_browser` 仍为 null 且视图仍处 loading）则兜底转为失败态并给出重试入口，消除插件原生创建静默失败时的无限空白无反馈。
- **retry 强制重建**：失败重试时若控制器不存在（原生创建失败场景），先把 WebView 移出控件树、延时 100ms 后放回，强制重建 `InAppWebView` 重新走完整创建流程，而非对空控制器调用 reload。

> 注意：基础版 `kDebugMode=false` 使 `isInspectable=false`，仅影响开发者工具开关，原生层不映射该开关到加载行为，排除嫌疑；Windows runner、路由、binding 两版一致，亦排除。

### 网页自动获取 Cookie（新增移植）

移植开发版的内置浏览器 Cookie 抓取功能并修复其返回闪退 bug：

- **开发版闪退根因**：抓取页无 `PopScope` 保护，AppBar 返回键/系统返回直接 `Navigator.pop`，带着仍活跃的 `InAppWebView` 平台视图（PlatformView）走路由转场动画；视图在转场动画帧中被引擎合成器销毁，Windows 上触发 `flutter_windows.dll` 内的访问违规崩溃。开发版仅在「捕获成功」路径手动做了移出控件树处理，返回/取消路径完全裸奔。
- **闪退修复（开发版同步修正）**：新增 `PopScope(canPop: false)` 拦截一切 pop 路径（AppBar 返回键、系统返回、程序化 pop），统一走 `_safeClose`：置 `_closing` 守卫防重入 → 先 `setState(_showWebView = false)` 把 WebView 移出控件树 → `stopLoading` + `dispose` → 等待 500ms 若干帧 → 再 `Navigator.pop(result)`。捕获成功路径同样收敛到 `_safeClose`。
- **移植内容**：新增 `web_cookie_capture.dart`（抓取页 + `kCookieCaptureTargets` 五平台配置 + Cookie 组装）、`cookie_validator.dart`（douyin/twitch 登录态接口校验，其余平台 unverified）、`core/common/cookie_string.dart`（Cookie 串解析/域名匹配工具）。
- **入口接入**：`AccountCookieEditorPage` 新增可选 `autoCaptureTarget` 参数，非空时在保存按钮旁显示「自动获取」按钮；抖音/虎牙/快手/SOOP/Twitch 五个 Cookie 设置页传入对应平台配置，捕获成功后自动填入并走保存链路（与开发版行为一致）。
