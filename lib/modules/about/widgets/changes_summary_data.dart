# 修改总结（相对上游原始版本）

本分支基于上游原始版本 **liuchuancong/pure_live v3.1.4** 修改而来，仓库地址：[ZXS20240220/pure_live · dev_from_v3.1.4](https://github.com/ZXS20240220/pure_live/tree/dev_from_v3.1.4)。

修改内容分两大类：**项目本身的取舍调整**（平台精简、依赖裁剪）与**开发版独有功能的移植**。以下按功能域归纳，仅描述最终效果；未列出的部分与上游保持一致。

---

## 一、项目定位与整体调整

- **仅支持 Windows 桌面平台**：移除其他平台目录与代码路径，界面交互按桌面习惯设计（鼠标悬停、右键菜单、键盘快捷键、窗口缩放）。
- **移除 Firebase**：不使用任何云后端服务。
- **移除竖屏直播适配**：替换为单一的「沉浸模式布局」设置（普通模式 ⇄ 沉浸模式）。
- **开发版功能移植**：数据模型、平台数据层、刷新体系、播放器、收藏/历史/换台、备份与远程同步等六大域。

---

## 二、数据模型与基础设施

- **直播间模型**：新增主播等级、公会名称、开播时间、地理位置等展示字段；刷新采用「新值非空才覆盖」的增量合并，避免空数据抹掉缓存。
- **弹幕消息**：新增用户等级与粉丝牌（名称/等级）字段，斗鱼、虎牙、抖音、B 站统一支持。
- **基础工具**：HTML 标题/简介清洗、输入焦点检测（快捷键守卫）、可中断异步任务池、横向页面滚轮映射、启动初始化并行提速。

---

## 三、平台数据层

| 平台 | 显示增强 |
| ---- | ---- |
| 斗鱼 | AI 看点摘要、主播卡片（粉丝数 / 等级 / 公会 / 开播时间） |
| 虎牙 | 公会名、粉丝数、主播等级、开播时间 |
| Bilibili | 主播等级、订阅数、开播时间；标题自动清洗 |
| 抖音 | 开播时间、IP 属地、粉丝数 |

---

## 四、刷新体系

- **平台级刷新配置**：各平台可单独设置刷新并发数与自动刷新间隔。
- **刷新成功保护**（0~60 秒可配置）：冷却期内所有刷新入口直接复用当前数据，全局防连点。
- **刷新失败保护**（0~60 分钟可配置）：自动刷新定时器跳过近期失败房间；手动刷新、下拉刷新、启动刷新等主动操作不受影响。
- **收藏 / 历史刷新**：按平台分组并发执行；启动校验覆盖观看历史；历史页与换台面板共用统一刷新入口。
- **遮罩语义**：全平台全标签时显示「正在刷新全部」，筛选状态显示「正在刷新当前筛选」。
- **桌面宽屏下拉刷新**：收藏页在任意窗口宽度下均可下拉刷新。
- **分页断点不刷新**：窗口跨越 680px 断点时仅切换分页模式，不触发数据刷新。
- **斗鱼 AI 看点自动轮询**：直播过程中新看点定时自动出现，无新内容时自动跳过请求。

---

## 五、播放器与播放页

### 播放内核

- **统一播放器接口**：支持进度查询、时移 seek、回到直播边缘等播放能力。
- **仅保留 mpv（media_kit）内核**：引擎选择为只读展示，历史内核设置自动归一；内核设置页的网络代理、GPU 解码、RTX VSR、mpv 高级设置均保留。
- **直播时移回放**：进度条可在已缓冲区间内拖动回看，起点动态对齐最早可回看位置，左侧时间显示进房累计时长；拖动自动吸附缓冲区防止重连，支持快速拖动与松手精确定位，「回到直播」一键返回实时画面。
- **缓冲调优**：前向缓存 150MB、回退缓存 256MB、预读 5 秒，长时间回看不触发重连。
- **清晰度标签全平台中文化**：B 站显示杜比 / 4K / 原画 / 蓝光等，抖音、SOOP 等按档位映射，Twitch 显示如「1080P60（原画）」；无法识别时按分辨率或码率生成可读标签；换档确认前显示「未确认 · 档位」过渡提示。

### 布局与交互

- **侧边栏宽度可拖拽**：播放页侧栏自由调整宽度并持久化，普通与沉浸两种模式均生效；仅窗口边缘可缩放窗口。
- **沉浸模式**：视频全屏铺满，侧栏随鼠标移入滑入、移出隐藏，面板透明度可调（滚轮 / 滑块）并支持锁定常驻。
- **直播截屏**：播放器左侧常驻截屏按钮（跟随控件栏显隐），支持快捷键 `Ctrl+S`；截取原始直播画面（不含弹幕与控件）保存为 png，文件名「平台-主播_时间戳.png」；保存目录可在设置中指定，并随备份 / 远程同步互通。
- **键盘快捷键**：输入框聚焦时不误触。
- **音量控制**：滚轮与拖动平滑调节。

### 弹幕列表

- **滚轮上滚即暂停自动跟随**，显示「回到底部」按钮并累计未读条数，滚回底部自动恢复跟随。
- **鼠标拖拽滚动**，拖拽中不受新弹幕干扰。
- **清屏按钮**：悬停显示，二次确认。
- **徽章渲染**：用户等级徽章 + 粉丝牌徽章；支持虎牙系统消息与斗鱼活动弹幕屏蔽。

### 稳定性

- 直播画面四周无缩放热区，窗口缩放 / 全屏切换不黑闪。
- 下播或连接失败时侧栏正常显示。
- 连续刷新不会导致内容消失；视频设置页渲染完整。

