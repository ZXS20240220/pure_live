- **密度档位**：新增「正常 / 较多 / 重叠」三档对齐 B 站策略：较多 = 轨道安全间距减半；重叠 = 间距减半 + 允许同轨重叠（安全间距全占用时回退最空闲轨道而非丢弃）+ 整体透明度降至 55%，海量弹幕下按需取舍密度与可读性。
- **安全间距修复**：轨道安全间距由固定 40px 改为随弹幕字号自适应（字号 ×1.5，限制 16~40px），大字号下不再误判重叠。

