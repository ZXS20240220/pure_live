## 八、搜索与账号

- **内嵌网页地址栏**：网页搜索、Cookie 抓取、B 站网页登录三个内嵌网页共用统一地址栏，实时展示当前网址；点击全选可直接编辑，回车或点跳转按钮加载新地址（自动补全 `https://` 前缀并校验合法性），右侧按钮一键复制；编辑中外部网址变化不回写，失焦未提交自动还原为实际网址。
- **网页搜索**：WebView 创建失败时 10 秒内给出失败页与重试入口，重试自动重建；加载进度以地址栏下方的独立窄条展示，不遮挡网页内容；网页区域结构对齐 Cookie 抓取页（WebView 直接挂载），修复网页内容加载后整体黑屏的问题。
- **WebView 崩溃自恢复**：监听渲染 / GPU 进程失败事件并记录日志，进程崩溃后自动 reload 恢复内容（连续崩溃 3 次后转为失败页等待手动重试）；AppBar 提供「重建页面」按钮，画面异常时可强制销毁并重建 WebView 控件自救。
- **Cookie 自动获取**：抖音、虎牙、快手、SOOP、Twitch 的 Cookie 设置页提供「自动获取」按钮，内置浏览器登录后一键回填保存。
- **WebView 解析代理**：所有无头 WebView 解析统一经共享队列串行执行，并按设置应用应用代理，修复配置代理后部分站点解析仍直连导致加载失败的问题。

