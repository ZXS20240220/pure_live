## 四、刷新体系

- **平台级刷新配置**：各平台可单独设置刷新并发数与自动刷新间隔。
- **刷新成功保护**（0~60 秒可配置）：冷却期内所有刷新入口直接复用当前数据，全局防连点。
- **刷新失败保护**（0~60 分钟可配置）：自动刷新定时器跳过近期失败房间；手动刷新、下拉刷新、启动刷新等主动操作不受影响。
- **收藏 / 历史刷新**：按平台分组并发执行；启动校验覆盖观看历史；历史页与换台面板共用统一刷新入口。
