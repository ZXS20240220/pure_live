- **双卡片布局**：关注页可在「卡片网格」（封面 + 信息栏）与「紧凑列表」（大头像 + 主播名 + 标题 + 直播状态色标）之间一键切换，紧凑卡片采用半透明深色底 + 圆角细边框样式（与换台面板列表一致）；紧凑布局每页数量按窗口可容纳的行数自适应（下限 10），支持置顶徽章，布局偏好持久化并随备份同步。
- **暂时弃用分类**：关注页新增第 5 个页签「暂时弃用」，用于存放不再关注动态但也不想取关的"下沉直播间"。暂弃房间不参与自动刷新与启动校验（仅手动刷新时，在暂弃页签下可刷新暂弃房间本身，范围仍受平台 / 标签 / 搜索筛选影响，遮罩显示"正在刷新全部弃用 / 当前筛选弃用"），平时仅保留移入时的一次性信息留存（可记录上次直播时间）；卡片显示"已弃用"遮罩，左键点击会刷新一次该房间状态（刷新期间遮罩以转圈动画暂时替代"已弃用"标识，且动画有最短展示时长避免"点了没反应"），若发现正在直播则弹窗询问是否移出暂时弃用并打开直播间，右键信息弹窗仅展示留存静态数据，右上角固定"移出暂时弃用"按钮，点击后房间立即恢复正常刷新。通过工具栏"+"按钮在弹窗中批量勾选编辑（支持按主播名 / 标题 / 房间号搜索，以及直播平台、直播中 / 未直播 / 已弃用状态筛选）；移入暂弃时自动删除该房间的历史记录副本，移出时立即请求一次最新状态；暂弃列表随备份与远程同步完整互通。
- **直播间信息弹窗**：右键 / 长按弹窗展示完整直播间档案——观看时长与热度概览、直播间网页链接、分区 / 分类、直播状态、观众数据、粉丝数、公告、开播时间、主播等级、公会、上次观看时间等（有则显示、无则隐藏）；点击任意信息项一键复制；标题等长文本渐隐截断并带悬浮 tooltip；平台 logo 悬浮显示平台信息；信息来自点击直播间时的全量抓取并持久化，后续刷新按「新值非空才覆盖」增量补充，不会抹掉已有字段。
- **换台面板**：完整嵌入侧栏跟随宽高，「已开播 / 观看记录」双页签，鼠标拖拽滚动，双网格下拉刷新，置顶徽章（已开播 tab 紧凑列表行内显示于平台标签左侧），历史卡片删除按钮，右上角清空历史；右上角新增「卡片 / 列表」布局一键切换（列表为大头像 + 主播名 + 标题，右侧两行显示 pin 徽章 + 平台胶囊与橙色人气 / 历史时间的半透明圆角卡片样式，宽度允许时可多列），不再随侧栏宽度变窄自动切换布局；两种布局卡片均支持右键 / 长按弹出房间信息弹窗（与关注页一致）；卡片内截断文本均带鼠标悬浮 tooltip；布局偏好持久化并随备份同步。
- **历史页**：条目与收藏列表同步，仅显示开播中的直播记录。

