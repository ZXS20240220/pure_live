## 五、播放器与播放页

### 播放内核

- **统一播放器接口**：支持进度查询、时移 seek、回到直播边缘等播放能力。
- **仅保留 mpv（media_kit）内核**：引擎选择为只读展示，历史内核设置自动归一；内核设置页的网络代理、GPU 解码、RTX VSR、mpv 高级设置均保留。
- **直播时移回放**：进度条可在已缓冲区间内拖动回看，起点动态对齐最早可回看位置，左侧时间显示进房累计时长；拖动自动吸附缓冲区防止重连，支持快速拖动与松手精确定位，「回到直播」一键返回实时画面。
- **缓冲调优**：前向缓存 150MB、回退缓存 256MB、预读 5 秒，长时间回看不触发重连。
- **清晰度标签全平台中文化**：B 站显示杜比 / 4K / 原画 / 蓝光等，抖音、SOOP 等按档位映射，Twitch 显示如「1080P60（原画）」；无法识别时按分辨率或码率生成可读标签；换档确认前显示「未确认 · 档位」过渡提示。
- **首选清晰度 · 智能选择**：在设置首选清晰度列表顶部新增「智能选择」档位，自动读取设备所有显示器中的最大屏幕短边作为目标分辨率，从可用画质中挑选最低够用的一档（优先分辨率，同分辨率再比码率和 FPS）；多显示器环境取最高分辨率；录制画质选择同步复用同一套逻辑；画质层级关系硬编码为「原画 > 蓝光 > 超清 > 高清 > 标清 > 流畅」，即使平台只返回文字标签也能稳定区分，原画永远最高。

### 布局与交互

- **侧边栏宽度可拖拽**：播放页侧栏自由调整宽度并持久化，普通与沉浸两种模式均生效；仅窗口边缘可缩放窗口。
- **沉浸模式**：视频全屏铺满，侧栏随鼠标移入滑入、移出隐藏，面板透明度可调（滚轮 / 滑块）并支持锁定常驻。
- **直播截屏**：播放器左侧常驻截屏按钮（跟随控件栏显隐），支持快捷键 `Ctrl+S`；截取原始直播画面（不含弹幕与控件）保存为 png，文件名「平台-主播_时间戳.png」；保存目录可在设置中指定，并随备份 / 远程同步互通。
- **键盘快捷键**：输入框聚焦时不误触。
- **音量控制**：滚轮与拖动平滑调节。

### 弹幕列表

- **滚轮上滚即暂停自动跟随**，显示「回到底部」按钮并累计未读条数，滚回底部自动恢复跟随。
- **鼠标拖拽滚动**，拖拽中不受新弹幕干扰。
- **清屏按钮**：悬停显示，二次确认。
- **徽章渲染**：用户等级徽章 + 粉丝牌徽章；支持虎牙系统消息与斗鱼活动弹幕屏蔽。

### 飘屏弹幕

- **同屏上限可配置**：飘屏同屏数量上限由固定 48 提为用户设置（10~200，默认 48），带说明文字，随设置持久化并纳入备份链路。
- **重复弹幕聚合**：时间窗口内的重复刷屏弹幕不再逐条丢弃，而是合成「原文 ×N」单条显示（N 为窗口内实际条数，如「666 ×3」），携带首条发送者信息；与「重复弹幕过滤」并存且优先生效，两者共用同一时间窗口设置，本地发送的弹幕不参与聚合，关闭开关立即发射未聚合弹幕，切换直播间自动丢弃残留分组。
- **丢弃透明化**：弹幕洪峰超出承载被丢弃时，弹幕列表左上角显示灰色「已隐藏 N 条弹幕」徽标（鼠标可穿透、不遮挡操作，无丢弃时自动隐藏），切换直播间后重新统计。
